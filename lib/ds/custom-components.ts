/**
 * Custom components: your own components built on the design system, kept in
 * components/custom/ (never in components/ui, which the DS Manager sync replaces).
 *
 * Each file exports its component(s) and a `demo` (the same shape as the shadcn
 * demos), tags its parts with data-slot so the editor can select and restyle them,
 * and is listed in components/custom/index.ts, which scripts/design-system.ts
 * regenerates from the folder on every build.
 */

export const CUSTOM_DIR = "components/custom"
export const CUSTOM_INDEX = `${CUSTOM_DIR}/index.ts`

/** "Patient card" → "patient-card" */
export function toComponentId(name: string) {
  return name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}

/** "patient-card" → "PatientCard" */
export function toPascal(id: string) {
  return id
    .split("-")
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("")
}

const ident = (id: string) => id.replace(/-/g, "_")

/** components/custom/index.ts for the given component ids (file names without .tsx) */
export function customRegistrySource(ids: string[]): string {
  const sorted = [...new Set(ids)].sort()
  return `// Generated by scripts/design-system.ts from the files in components/custom. Don't edit by hand.
import type { Demo } from "@/components/editor/canvas/shadcn/types"
${sorted.map((id) => `import { demo as ${ident(id)} } from "./${id}"`).join("\n")}

export const CUSTOM_DEMOS: Demo[] = [${sorted.map(ident).join(", ")}]
`
}

/** Starter file for a new custom component */
export function scaffoldCustomComponent({ id, name, description }: { id: string; name: string; description: string }): string {
  const C = toPascal(id)
  const q = (s: string) => JSON.stringify(s)
  return `import * as React from "react"

import type { Demo } from "@/components/editor/canvas/shadcn/types"
import { cn } from "@/lib/utils"

/**
 * ${description.replace(/\*\//g, "")}
 *
 * Custom component: build it from components/ui and theme tokens, and give each
 * part a data-slot so it can be selected and restyled in the editor.
 */
export function ${C}({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot=${q(id)}
      className={cn("bg-card text-card-foreground flex flex-col gap-2 rounded-xl border p-6 shadow-sm", className)}
      {...props}
    />
  )
}

export function ${C}Title({ className, ...props }: React.ComponentProps<"h3">) {
  return <h3 data-slot=${q(`${id}-title`)} className={cn("font-heading text-lg font-semibold", className)} {...props} />
}

export function ${C}Description({ className, ...props }: React.ComponentProps<"p">) {
  return <p data-slot=${q(`${id}-description`)} className={cn("text-muted-foreground text-sm", className)} {...props} />
}

export const demo: Demo = {
  id: ${q(id)},
  name: ${q(name)},
  description: ${q(description)},
  examples: [
    {
      name: "Default",
      render: () => (
        <${C} className="w-full max-w-sm">
          <${C}Title>${name.replace(/[<>{}]/g, "")}</${C}Title>
          <${C}Description>Starter layout. Edit components/custom/${id}.tsx to build it out.</${C}Description>
        </${C}>
      ),
    },
  ],
}
`
}
